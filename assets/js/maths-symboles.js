/* Liste « à plat » pour l'autocomplétion : une entrée par code. */
window.MATHS_COMMANDES = (function () {
    const vus = new Set(), liste = [];
    window.MATHS_SYMBOLES.forEach(({ groupe, items }) => items.forEach(([label, code, desc]) => {
        const nom = (code.match(/^\\[a-zA-Z]+/) || [])[0];
        if (!nom || vus.has(code)) return;
        vus.add(code);
        liste.push({ nom, code, label, desc: desc || '', groupe });
    }));
    // Raccourcis ajoutés dans assets/js/mathjax-config.js
    [['\\R', 'ℝ', 'réels'], ['\\N', 'ℕ', 'entiers naturels'], ['\\Z', 'ℤ', 'entiers relatifs'],
     ['\\Q', 'ℚ', 'rationnels'], ['\\C', 'ℂ', 'complexes'], ['\\K', '𝕂', 'ℝ ou ℂ'],
     ['\\abs{‹x›}', '|x|', 'valeur absolue'], ['\\norm{‹u›}', '‖u‖', 'norme'],
     ['\\ens{‹a, b›}', '{…}', 'ensemble (accolades)'], ['\\dx', 'dx', 'élément différentiel'],
     ['\\eps', 'ε', 'epsilon']].forEach(([code, label, desc]) => {
        liste.push({ nom: code.match(/^\\[a-zA-Z]+/)[0], code, label, desc, groupe: 'Raccourcis' });
    });
    return liste;
})();
